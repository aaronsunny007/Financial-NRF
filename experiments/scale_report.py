"""Render results/scale/summary.json (from experiments.scale_analysis) as Markdown tables.

Usage:
    python -m experiments.scale_report [--summary results/scale/summary.json] [--out results/scale/SUMMARY.md]
"""

import argparse
import json
import math
from pathlib import Path


def f(x, d=2, sign=False):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def ci(c, d=2, sign=True):
    return f"[{f(c[0], d, sign)}, {f(c[1], d, sign)}]"


def pc(x):
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}%"


def render(s):
    runs = s["runs"]
    order = sorted(runs, key=lambda k: (runs[k]["model"], runs[k]["split"], str(runs[k]["seed"])))
    L = []
    L.append("# Scale-up results\n")
    L.append("Generated by `python -m experiments.scale_analysis` and `python -m experiments.scale_report` "
             f"({s['bootstrap_resamples']} bootstrap resamples over items). Every run is a CPU re-run with the "
             "corrected scorer; names are `<model>_<split>[_s<seed>]`, where `_s<n>` is a sampled-decoding seed "
             "(temperature 0.7) and no suffix is greedy.\n")

    L.append("## Headline: does the composite track noise, and does oracle evidence rank above retrieval?\n")
    L.append("| Run | Items | Accuracy retrieval / oracle | r(noise, composite) [95% CI] | r(noise, hallucination rate) | "
             "Oracle minus retrieval, accuracy [CI] | Oracle minus retrieval, composite [CI] | Weightings passing both [CI] |")
    L.append("|---|---|---|---|---|---|---|---|")
    for k in order:
        r = runs[k]
        if "exp5" not in r:
            continue
        L.append(f"| {k} | {r['n_items']} | {f(r['exp5']['retrieval']['accuracy'])} / {f(r['exp5']['oracle']['accuracy'])} | "
                 f"{f(r['r_noise_composite'], 2, True)} {ci(r['ci95']['r_noise_composite'])} | "
                 f"{f(r['r_noise_hallucination_rate'], 2, True)} | "
                 f"{f(r['oracle_minus_retrieval_accuracy'], 3, True)} {ci(r['ci95']['oracle_minus_retrieval_accuracy'], 3)} | "
                 f"{f(r['oracle_minus_retrieval_composite'], 3, True)} {ci(r['ci95']['oracle_minus_retrieval_composite'], 3)} | "
                 f"{pc(r['sweep']['both'])} [{pc(r['sweep_ci95']['both'][0])}, {pc(r['sweep_ci95']['both'][1])}] |")

    L.append("\n## Item-level noise effect (highest noise level minus 0%, paired within item)\n")
    L.append("A paired mean change with a bootstrap interval over items, which uses every item rather than five level averages.\n")
    metrics = ["accuracy", "evidence_support", "hallucination_flag", "support_vs_clean_evidence", "nli_frac_entailed"]
    L.append("| Run | " + " | ".join(m.replace("_", " ") for m in metrics) + " |")
    L.append("|---|" + "---|" * len(metrics))
    for k in [x for x in order if runs[x].get("mode") != "corrupt"]:
        e = runs[k]["item_level_noise_effects"]
        cells = []
        for m in metrics:
            if m in e:
                cells.append(f"{f(e[m]['mean_change'], 3, True)} {ci(e[m]['ci95'], 3)}")
            else:
                cells.append("not measured")
        L.append(f"| {k} | " + " | ".join(cells) + " |")

    L.append("\n## Can the measures tell a correct answer from an incorrect one? (clean condition)\n")
    L.append("Area under the ROC curve for separating correct from incorrect answers (0.5 is chance), with a bootstrap interval over items.\n")
    names = ["evidence_support_overlap", "no_hallucination_flag", "self_reported_confidence", "nli_frac_entailed"]
    L.append("| Run | overlap evidence support | no hallucination flag | self-reported confidence | entailment support |")
    L.append("|---|---|---|---|---|")
    for k in [x for x in order if runs[x].get("mode") != "corrupt"]:
        d = runs[k].get("discrimination_of_correctness", {})
        L.append(f"| {k} | " + " | ".join(
            (f"{f(d[m]['auroc'])} {ci(d[m]['ci95'], 2, False)}" if m in d else "not measured") for m in names) + " |")

    corrupt = [k for k in order if runs[k].get("mode") == "corrupt"]
    if corrupt:
        L.append("\n## Corrupted evidence (a share of the numbers in the retrieved evidence replaced by wrong ones)\n")
        L.append("Unlike the injected distractor sentences, this does degrade a model that trusts its evidence. "
                 "The question is which measures notice. Each column is the Pearson r with the corruption level over the "
                 "five levels, with a bootstrap interval over items.\n")
        L.append("| Run | Items | Accuracy at 0% / 100% | r(level, accuracy) | r(level, composite) [CI] | r(level, support vs shown evidence) | "
                 "r(level, support vs clean evidence) [CI] | r(level, hallucination rate) |")
        L.append("|---|---|---|---|---|---|---|---|")
        for k in corrupt:
            r = runs[k]
            L.append(f"| {k} | {r['n_items']} | {f(r['accuracy_by_level'][0])} / {f(r['accuracy_by_level'][-1])} | "
                     f"{f(r['r_noise_component']['accuracy'], 2, True)} | "
                     f"{f(r['r_noise_composite'], 2, True)} {ci(r['ci95']['r_noise_composite'])} | "
                     f"{f(r['r_noise_component']['faithfulness'], 2, True)} | "
                     f"{f(r['r_noise_support_vs_clean'], 2, True)} {ci(r['ci95']['r_noise_support_vs_clean'])} | "
                     f"{f(r['r_noise_hallucination_rate'], 2, True)} |")
        L.append("\nSame runs, item-level change from 0% to 100% corruption (paired within item):\n")
        L.append("| Run | accuracy | evidence support (shown) | hallucination flag | support vs clean evidence | nli frac entailed |")
        L.append("|---|---|---|---|---|---|")
        for k in corrupt:
            e = runs[k]["item_level_noise_effects"]
            L.append(f"| {k} | " + " | ".join(
                (f"{f(e[m]['mean_change'], 3, True)} {ci(e[m]['ci95'], 3)}" if m in e else "not measured")
                for m in ["accuracy", "evidence_support", "hallucination_flag", "support_vs_clean_evidence", "nli_frac_entailed"]) + " |")

    L.append("\n## Weights chosen on dev, evaluated on test\n")
    v = s.get("held_out_weight_validation", {})
    if v:
        L.append("| Model | Pass both on dev | Of those, pass both on test | Share passing both on test (all weightings) | Dev's pick among correct rankings: dev r, test r, ranks on test |")
        L.append("|---|---|---|---|---|")
        for m, r in v.items():
            ch = r.get("dev_choice_among_correct_rankings")
            pick = (f"{f(ch['dev_noise_r'], 2, True)}, {f(ch['test_noise_r'], 2, True)}, {ch['test_ranks_correctly']}"
                    if ch else "none ranks correctly")
            L.append(f"| {m} | {r['n_pass_both_on_dev']} ({pc(r['share_pass_both_dev'])}) | "
                     f"{pc(r['of_those_pass_both_on_test']) if 'of_those_pass_both_on_test' in r else 'nothing to validate'} | "
                     f"{pc(r['share_pass_both_test'])} | {pick} |")
    else:
        L.append("No model has both a dev and a test run yet.")

    L.append("\n## Spread across decoding seeds (same model, sampled at temperature 0.7)\n")
    sp = s.get("seed_spread", {})
    if sp:
        L.append("Each seed is a separate sampled run on the same items. The spread shows how much of a single run's number is "
                 "generation luck.\n")
        L.append("| Model | Runs | r(noise, composite) mean ± sd | r(noise, hallucination) mean ± sd | Clean accuracy mean ± sd | "
                 "Accuracy change under noise mean ± sd | Share of weightings passing both |")
        L.append("|---|---|---|---|---|---|---|")
        def ms(x, d=2, sign=False):
            if not x:
                return "n/a"
            return f"{f(x['mean'], d, sign)} ± {f(x['sd'], d)}"
        for m, r in sp.items():
            both = r.get("share_pass_both")
            if not both:
                both_s = "needs Experiment 5 (not run)"
            elif both.get("n", 0) < 2:
                both_s = f"{pc(both['mean'])} (only one run reached Experiment 5)"
            else:
                both_s = f"{pc(both['mean'])} ± {pc(both['sd'])}"
            L.append(f"| {m} | {r['n_runs']} | {ms(r['r_noise_composite'], 2, True)} | {ms(r['r_noise_hallucination_rate'], 2, True)} | "
                     f"{ms(r['accuracy_clean'])} | {ms(r['accuracy_change_noise'], 3, True)} | {both_s} |")
    else:
        L.append("Fewer than three sampled runs are available for any model.")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", type=Path, default=Path("results/scale/summary.json"))
    ap.add_argument("--out", type=Path, default=Path("results/scale/SUMMARY.md"))
    a = ap.parse_args()
    s = json.load(open(a.summary))
    a.out.write_text(render(s))
    print(f"Wrote {a.out}")


if __name__ == "__main__":
    main()
